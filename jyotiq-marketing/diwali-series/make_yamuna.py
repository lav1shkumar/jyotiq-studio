"""Make diwali/shared/yamuna.tsx from Manthan Ep6's MohiniStanding (ep6/mohini.tsx), read-only, by palette swap.

Yamuna (Kalindi, the dark river) keeps the series' female figure, face and finish, re-dressed:
dark shyama skin, a royal-blue saree with a silver wave border and a gold choli. Mohini's file is not edited.
Usage: /usr/local/bin/python3 /Users/ayushrajput/.kiro/crew/workspace/jyotiq-marketing/diwali-series/make_yamuna.py
"""
from pathlib import Path

SRC = Path("/Users/ayushrajput/.kiro/crew/workspace/video/src/Jyotiq/manthan/ep6/mohini.tsx")
DST = Path("/Users/ayushrajput/.kiro/crew/workspace/video/src/Jyotiq/diwali/shared/yamuna.tsx")

t = SRC.read_text()
swaps = [
    ('from "../rig"', 'from "../../manthan/rig"'),
    ('from "../style"', 'from "../../manthan/style"'),
    ("MohiniStanding", "YamunaStanding"),
    ("MohiniProps", "YamunaProps"),
    ('skin: "#4A78DC", skinShade: "#2F55AE", skinLine: "#1A2F6A", rim: "#C8E4FF",',
     'skin: "#3A4A72", skinShade: "#27345A", skinLine: "#121C30", rim: "#B8CCF2",'),
    ('sari: "#F2B81E", sariShade: "#C98A0C", sariHi: "#FFD964", choli: "#1F6B4A",',
     'sari: "#2B4FA8", sariShade: "#1C357A", sariHi: "#6A8FE0", choli: "#C8892A",'),
    ('const BORDER = "#E0457F";', 'const BORDER = "#DDE6F2";'),
]
missing = [a for a, _ in swaps if a not in t]
if missing:
    raise SystemExit(f"mohini.tsx changed; these anchors were not found: {missing}")
for a, b in swaps:
    t = t.replace(a, b)
header = ("// Generated by jyotiq-marketing/diwali-series/make_yamuna.py from manthan/ep6/mohini.tsx (MohiniStanding),\n"
          "// palette-swapped for Yamuna: dark shyama skin, a royal-blue saree with a silver wave border, a gold choli.\n")
DST.parent.mkdir(parents=True, exist_ok=True)
DST.write_text(header + t)
print("wrote", DST, len(t.splitlines()), "lines; YamunaStanding exported:", "export const YamunaStanding" in t)
