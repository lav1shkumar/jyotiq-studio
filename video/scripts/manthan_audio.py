#!/usr/bin/env python3
"""Manthan Ep1 - timeline + audio mix (single source of truth).

1. Writes src/Jyotiq/manthan/timing.ts (VO start frames, scene ranges,
   SFX cue frames) so picture and sound share one clock.
2. Mixes the 10 trimmed ElevenLabs lines, Ayush's 3 ElevenLabs SFX
   (thunder, volcano, water) and a synthesized bed (tanpura-like drone +
   low air) plus small synthesized accents (booms, whooshes, shimmers) into
   public/jyotiq/manthan/mix.wav, with the bed/SFX ducked under dialogue and
   the master normalised to about -14 LUFS for Instagram.

ffmpeg only (no numpy on this Mac).
"""
import json
import re
import subprocess
from pathlib import Path

ROOT = Path("/Users/ayushrajput/.kiro/crew/workspace/video")
SFX_DIR = Path("/Users/ayushrajput/.kiro/crew/workspace/manthan-ep1/audio/sfx")
VO_DIR = ROOT / "public/jyotiq/manthan/vo"
OUT = ROOT / "public/jyotiq/manthan/mix.wav"
TS = ROOT / "src/Jyotiq/manthan/timing.ts"
FPS = 30
TOTAL = 2070  # frames (69.0 s)

# ---- dialogue: line -> start frame -----------------------------------
VO_AT = {
    "01_narrator": 6,     # hook: "Ek asur itna chatur tha..."
    "02_narrator": 204,   # "Aur aaj bhi... aapki kundali mein"
    "03_durvasa": 426,    # garland offering
    "04_indra": 556,      # "Airavat... ise tum sambhalo"
    "05_durvasa": 752,    # the curse
    "06_narrator": 1004,  # "Shakti gayi... swarg asuron ka"
    "07_narrator": 1150,  # Swarbhanu plant
    "08_indra": 1414,     # "Prabhu, hamein bachaiye!"
    "09_vishnu": 1502,    # the plan
    "10_swarbhanu": 1742, # cliffhanger
}

# ---- picture: scene ranges (frames) ----------------------------------
SCENES = {
    "hook": (0, 204),
    "kundali": (204, 336),
    "title": (336, 396),
    "swarga": (396, 746),
    "curse": (746, 990),
    "invasion": (990, 1140),
    "swarbhanu": (1140, 1388),
    "ksheer": (1388, 1500),
    "plan": (1500, 1730),
    "court": (1730, 1900),
    "end": (1900, TOTAL),
}

# ---- accents the picture syncs to (frames) ----------------------------
CUES = {
    "nameCard": 150,       # SWARBHANU card slams in
    "eclipse": 262,        # sun/moon eclipse on "kundali"
    "titleHit": 336,
    "swargaBells": 398,
    "garlandToss": 650,
    "stomp1": 712,
    "stomp2": 726,
    "thunder1": 752,       # impact frame on "Ahankari Indra!"
    "thunder2": 868,       # second strike mid-curse
    "drain": 953,          # colour drains after the curse
    "volcano": 984,        # asura assault, heaven burns
    "riser": 1140,         # push-in on Swarbhanu
    "eyeGlint": 1330,
    "waterSwell": 1380,
    "vishnuReveal": 1481,
    "planDraw": 1560,
    "freeze": 1891,        # cliffhanger freeze-frame
    "endCard": 1906,
}


def sec(f):
    return f / FPS


def ms(f):
    return int(round(f * 1000 / FPS))


def write_timing(vo_frames):
    lines = [
        "// Generated by scripts/manthan_audio.py - edit timings THERE so picture and sound stay in sync.",
        f"export const FPS = {FPS};",
        f"export const TOTAL = {TOTAL};",
        "export type Range = readonly [number, number];",
        "/** Dialogue line -> [start, end) frames on the reel clock. */",
        "export const LINES: Record<string, Range> = {",
    ]
    for k, a in VO_AT.items():
        lines.append(f'  "{k}": [{a}, {a + vo_frames[k]}],')
    lines.append("};")
    lines.append("export const SCENES = {")
    for k, (a, b) in SCENES.items():
        lines.append(f"  {k}: [{a}, {b}] as Range,")
    lines.append("};")
    lines.append("export const CUES = {")
    for k, v in CUES.items():
        lines.append(f"  {k}: {v},")
    lines.append("};")
    TS.write_text("\n".join(lines) + "\n")


def vo_frames():
    t = (ROOT / "src/Jyotiq/manthan/voData.ts").read_text()
    data = json.loads(t.split("VoLine> = ", 1)[1].strip().rstrip(";"))
    return {k: v["frames"] for k, v in data.items()}


def build_graph():
    """Returns (inputs, filtergraph)."""
    inputs = []
    g = []
    vo_labels = []
    for i, (k, a) in enumerate(VO_AT.items()):
        inputs += ["-i", str(VO_DIR / f"{k}.wav")]
        chain = f"[{i}:a]highpass=f=75,acompressor=threshold=0.12:ratio=2.5:attack=8:release=160:makeup=1.6"
        if k == "09_vishnu":  # temple-like space for the divine voice
            chain += ",aecho=0.8:0.55:70|140:0.28|0.16"
        if k.startswith("05_durvasa"):  # the curse rings out
            chain += ",aecho=0.8:0.5:90:0.22"
        if k == "10_swarbhanu":  # intimate, close, slightly darker
            chain += ",equalizer=f=180:t=q:w=1.2:g=2.5"
        chain += f",adelay={ms(a)}|{ms(a)}[v{i}]"
        g.append(chain)
        vo_labels.append(f"[v{i}]")
    n = len(VO_AT)
    g.append(f"{''.join(vo_labels)}amix=inputs={n}:normalize=0,apad=whole_dur={sec(TOTAL)},asplit=2[vo][vosc]")

    # ---- Ayush's ElevenLabs SFX ------------------------------------
    sfx = {"thunder": n, "volcano": n + 1, "water": n + 2}
    for name in ("thunder", "volcano", "water"):
        inputs += ["-i", str(SFX_DIR / f"sfx_{name}.mp3")]

    def clip(idx, src_a, src_b, at_f, gain, fin, fout, label):
        d = src_b - src_a
        g.append(
            f"[{idx}:a]atrim={src_a}:{src_b},asetpts=PTS-STARTPTS,aresample=48000,"
            f"afade=t=in:d={fin},afade=t=out:st={d - fout:.3f}:d={fout},volume={gain},"
            f"adelay={ms(at_f)}|{ms(at_f)}[{label}]"
        )
        return f"[{label}]"

    fx = []
    # thunder: we need it in two places (curse + title), so split the input
    g.append(f"[{sfx['thunder']}:a]asplit=2[thA][thB]")
    g.append(
        f"[thA]atrim=0:9.6,asetpts=PTS-STARTPTS,aresample=48000,afade=t=in:d=0.01,afade=t=out:st=7.4:d=2.2,"
        f"volume=0.9,adelay={ms(CUES['thunder1'] - 4)}|{ms(CUES['thunder1'] - 4)}[th1]"
    )
    g.append(
        f"[thB]atrim=12.8:15.6,asetpts=PTS-STARTPTS,aresample=48000,afade=t=in:d=0.02,afade=t=out:st=1.6:d=1.2,"
        f"volume=0.42,adelay={ms(CUES['titleHit'] - 2)}|{ms(CUES['titleHit'] - 2)}[th2]"
    )
    fx += ["[th1]", "[th2]"]
    fx.append(clip(sfx["volcano"], 0, 10.5, CUES["volcano"], 0.75, 0.25, 3.0, "vol"))
    fx.append(clip(sfx["water"], 1.5, 15.5, CUES["waterSwell"], 0.85, 1.2, 4.0, "wat"))

    # ---- synthesized accents ----------------------------------------
    def boom(at_f, amp, f0=42, f1=34, dec=2.6, label="b"):
        d = 2.4
        g.append(
            f"aevalsrc='{amp}*sin(2*PI*({f0}+{f1}*exp(-t*9))*t)*exp(-t*{dec})|{amp}*sin(2*PI*({f0}+{f1}*exp(-t*9))*t)*exp(-t*{dec})'"
            f":s=48000:d={d},lowpass=f=180,adelay={ms(at_f)}|{ms(at_f)}[{label}]"
        )
        return f"[{label}]"

    def whoosh(at_f, amp, dur=0.7, label="w"):
        g.append(
            f"anoisesrc=color=pink:amplitude=1:d={dur}:r=48000,bandpass=f=900:w=1400,"
            f"volume='{amp}*sin(PI*t/{dur})^2':eval=frame,aformat=channel_layouts=stereo,"
            f"adelay={ms(at_f)}|{ms(at_f)}[{label}]"
        )
        return f"[{label}]"

    def shimmer(at_f, amp, base=1320, dur=3.0, label="s"):
        e = "+".join(f"{a}*sin(2*PI*{base * r}*t)*exp(-t*{k})" for a, r, k in ((0.5, 1, 1.4), (0.3, 1.5, 1.8), (0.22, 2, 2.2), (0.15, 3, 2.8)))
        g.append(
            f"aevalsrc='{amp}*({e})|{amp}*({e})':s=48000:d={dur},aecho=0.8:0.6:120|240:0.35|0.2,"
            f"adelay={ms(at_f)}|{ms(at_f)}[{label}]"
        )
        return f"[{label}]"

    fx.append(whoosh(CUES["nameCard"] - 12, 0.5, 0.5, "w1"))
    fx.append(boom(CUES["nameCard"], 0.55, label="b1"))
    fx.append(shimmer(CUES["eclipse"], 0.10, 990, 3.5, "s1"))
    fx.append(boom(CUES["titleHit"], 0.6, 38, 40, 1.8, "b2"))
    fx.append(shimmer(CUES["swargaBells"], 0.12, 1180, 3.6, "s2"))
    fx.append(whoosh(CUES["garlandToss"], 0.35, 0.6, "w2"))
    fx.append(boom(CUES["stomp1"], 0.5, 55, 25, 6, "b3"))
    fx.append(boom(CUES["stomp2"], 0.55, 50, 25, 6, "b4"))
    fx.append(whoosh(CUES["riser"] - 6, 0.45, 1.6, "w3"))
    fx.append(shimmer(CUES["eyeGlint"], 0.09, 1560, 2.4, "s3"))
    fx.append(shimmer(CUES["vishnuReveal"], 0.16, 880, 4.5, "s4"))
    fx.append(shimmer(CUES["planDraw"], 0.07, 1320, 3.0, "s5"))
    fx.append(whoosh(CUES["freeze"] - 10, 0.5, 0.45, "w4"))
    fx.append(boom(CUES["freeze"], 0.7, 36, 44, 1.5, "b5"))
    fx.append(shimmer(CUES["endCard"], 0.13, 1046, 4.0, "s6"))

    # ---- bed: tanpura-like drone (Sa-Pa on A) + low air --------------
    T = sec(TOTAL)
    drone = (
        "0.30*sin(2*PI*110*t)*(0.75+0.25*sin(2*PI*0.21*t))"
        "+0.18*sin(2*PI*165*t)*(0.7+0.3*sin(2*PI*0.17*t+1))"
        "+0.14*sin(2*PI*220*t)*(0.6+0.4*sin(2*PI*0.29*t+2))"
        "+0.07*sin(2*PI*330.6*t)*(0.5+0.5*sin(2*PI*0.37*t))"
        "+0.05*sin(2*PI*440.4*t)*(0.5+0.5*sin(2*PI*0.43*t+0.5))"
        "+0.12*sin(2*PI*55*t)"
    )
    g.append(f"aevalsrc='{drone}|{drone}':s=48000:d={T},lowpass=f=1400,aecho=0.8:0.7:180|360:0.3|0.2[drn]")
    g.append(f"anoisesrc=color=brown:amplitude=0.5:d={T}:r=48000,lowpass=f=320,aformat=channel_layouts=stereo[air]")
    # scene-aware bed level: softer in Swarga, heavier in curse/invasion/court, out under the freeze
    lvl = (
        f"if(lt(t,{sec(396)}),0.30,"
        f"if(lt(t,{sec(746)}),0.20,"
        f"if(lt(t,{sec(1140)}),0.34,"
        f"if(lt(t,{sec(1388)}),0.30,"
        f"if(lt(t,{sec(1730)}),0.24,"
        f"if(lt(t,{sec(CUES['freeze'])}),0.32,0.18))))))"
    )
    g.append(f"[drn][air]amix=inputs=2:normalize=0:weights=1 0.55,volume='{lvl}':eval=frame,afade=t=in:d=0.25,afade=t=out:st={T - 1.6}:d=1.6[bed]")

    # ---- buses -------------------------------------------------------
    g.append(f"[bed]{''.join(fx)}amix=inputs={len(fx) + 1}:normalize=0,apad=whole_dur={T}[bus]")
    g.append("[bus][vosc]sidechaincompress=threshold=0.03:ratio=5:attack=15:release=380:makeup=1[duck]")
    g.append(
        f"[vo][duck]amix=inputs=2:normalize=0,atrim=0:{T},"
        "loudnorm=I=-14:TP=-1.5:LRA=9,aresample=48000[out]"
    )
    return inputs, ";\n".join(g)


def main():
    vf = vo_frames()
    write_timing(vf)
    for k, a in VO_AT.items():
        print(f"{k}: {a}-{a + vf[k]}  ({sec(a):.2f}-{sec(a + vf[k]):.2f}s)")
    # sanity: no dialogue overlaps
    spans = sorted((a, a + vf[k], k) for k, a in VO_AT.items())
    for (a1, b1, k1), (a2, _, k2) in zip(spans, spans[1:]):
        assert b1 <= a2, f"overlap {k1} / {k2}"
    inputs, graph = build_graph()
    gp = OUT.parent / "mix_graph.txt"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    gp.write_text(graph)
    r = subprocess.run(
        ["ffmpeg", "-hide_banner", "-v", "error", "-y", *inputs, "-/filter_complex", str(gp),
         "-map", "[out]", "-ac", "2", "-ar", "48000", "-c:a", "pcm_s16le", str(OUT)],
        capture_output=True, text=True,
    )
    if r.returncode:
        print(r.stderr[-3000:])
        raise SystemExit(1)
    m = subprocess.run(["ffmpeg", "-hide_banner", "-i", str(OUT), "-af", "ebur128=peak=true", "-f", "null", "-"],
                       capture_output=True, text=True).stderr
    summ = m.split("Summary:")[-1]
    i = re.search(r"I:\s+(-?[0-9.]+) LUFS", summ)
    lra = re.search(r"LRA:\s+([0-9.]+) LU", summ)
    pk = re.search(r"Peak:\s+(-?[0-9.]+) dBFS", summ)
    print(f"wrote {OUT}  I={i and i.group(1)} LUFS  LRA={lra and lra.group(1)}  TP={pk and pk.group(1)} dBFS")


if __name__ == "__main__":
    main()
