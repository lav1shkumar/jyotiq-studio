#!/usr/bin/env python3
"""Manthan Ep1 voice prep.

For each ElevenLabs line: trim leading/trailing silence (keeping a short
natural pad), write a 48 kHz stereo WAV into public/jyotiq/manthan/vo/, and
measure a per-frame (30 fps) loudness envelope used to drive the puppets'
mouths. Writes src/Jyotiq/manthan/voData.ts.

Standard library only (no numpy on this Mac).
"""
import json
import re
import subprocess
from pathlib import Path

SRC = Path("/Users/ayushrajput/.kiro/crew/workspace/manthan-ep1/audio/vo")
ROOT = Path("/Users/ayushrajput/.kiro/crew/workspace/video")
OUT = ROOT / "public/jyotiq/manthan/vo"
TS = ROOT / "src/Jyotiq/manthan/voData.ts"
FPS = 30
SR = 48000
PAD = 0.06  # seconds of air kept before/after speech


def run(cmd):
    return subprocess.run(cmd, capture_output=True, text=True)


def speech_bounds(path: Path):
    """First/last non-silent instants via silencedetect (-45 dB, 80 ms)."""
    r = run(["ffmpeg", "-hide_banner", "-i", str(path), "-af", "silencedetect=n=-45dB:d=0.08", "-f", "null", "-"])
    dur = float(run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(path)]).stdout)
    starts = [float(x) for x in re.findall(r"silence_start: ([0-9.]+)", r.stderr)]
    ends = [float(x) for x in re.findall(r"silence_end: ([0-9.]+)", r.stderr)]
    head = 0.0
    if starts and starts[0] <= 0.02 and ends:
        head = ends[0]
    tail = dur
    if starts and (not ends or starts[-1] > ends[-1]):
        tail = starts[-1]
    return max(0.0, head - PAD), min(dur, tail + PAD), dur


def envelope(path: Path):
    """Per-frame RMS (dB) -> 0..1 mouth openness."""
    n = SR // FPS
    r = run([
        "ffmpeg", "-hide_banner", "-i", str(path), "-af",
        f"aresample={SR},pan=mono|c0=0.5*c0+0.5*c1,asetnsamples=n={n}:p=0,astats=metadata=1:reset=1,"
        "ametadata=print:key=lavfi.astats.Overall.RMS_level",
        "-f", "null", "-",
    ])
    vals = []
    for m in re.findall(r"RMS_level=(-?[0-9.]+|-inf)", r.stderr):
        db = -90.0 if m == "-inf" else float(m)
        # -42 dB = shut, -14 dB = wide open
        v = (db + 42.0) / 28.0
        vals.append(round(max(0.0, min(1.0, v)), 2))
    return vals


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    TS.parent.mkdir(parents=True, exist_ok=True)
    data = {}
    for f in sorted(SRC.glob("*.mp3")):
        a, b, dur = speech_bounds(f)
        wav = OUT / f"{f.stem}.wav"
        run([
            "ffmpeg", "-v", "error", "-y", "-ss", f"{a:.3f}", "-to", f"{b:.3f}", "-i", str(f),
            "-af", "afade=t=in:d=0.02,areverse,afade=t=in:d=0.04,areverse",
            "-ar", str(SR), "-ac", "2", str(wav),
        ])
        env = envelope(wav)
        frames = len(env)
        data[f.stem] = {"file": f"jyotiq/manthan/vo/{wav.name}", "frames": frames, "sec": round(frames / FPS, 3), "env": env}
        print(f"{f.stem}: src {dur:.2f}s  trim {a:.2f}-{b:.2f}  -> {frames} frames ({frames / FPS:.2f}s)")
    body = json.dumps(data, separators=(",", ":"))
    TS.write_text(
        "// Generated by scripts/manthan_vo_prep.py - do not edit by hand.\n"
        "// Per line: trimmed WAV path, length in frames (30 fps) and a 0..1 mouth envelope per frame.\n"
        "export type VoLine = { file: string; frames: number; sec: number; env: number[] };\n"
        f"export const VO: Record<string, VoLine> = {body};\n"
    )
    print("wrote", TS)


if __name__ == "__main__":
    main()
