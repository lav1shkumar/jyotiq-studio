import React from "react";
import { World } from "../../manthan/kit";
import { KshiraSagar, Motes, Vignette } from "../../manthan/sets";
import { CINZEL } from "../../manthan/graphics";
import { ramp, track, W } from "../../manthan/style";
import { CounterDefs, JewellerCounter } from "./counter";
import { DiyaDefs, DiyaRow, slotX } from "./diya";
import { MarketDefs } from "./market";
import { CUES, SCENES } from "./timing";

/* Diwali Day 1 scenes, part A: the hook (01) and the Manthan sea with the five diyas (title + 02).
   One clock: timing.ts (generated by scripts/diwali_d1_audio.py from the real takes). */

const cue = (k: string, dflt: number): number => (typeof CUES[k] === "number" ? CUES[k] : dflt);

/** All Day 1 svg defs on top of World's own (RigDefs, SetDefs). */
export const D1Defs: React.FC = () => (
  <>
    <CounterDefs />
    <MarketDefs />
    <DiyaDefs />
  </>
);

/* ------------------------------------------------------------------ */
/* 01 hook: the jeweller's counter, lit from frame 0                    */
/* ------------------------------------------------------------------ */

export const HookD1: React.FC<{ f: number }> = ({ f }) => {
  const [, end] = SCENES.hook;
  const push = track(f, [[0, 0.05], [end, 0.75, "io"]]);
  const reach = 0.55 + 0.45 * ramp(f, 0, cue("kharid01", 50) + 12, "out");
  const N = cue("nahi", 185);
  const D = cue("dissolve", 219);
  const glint = 0.05 + 0.95 * ramp(f, N - 2, D + 6, "in");
  return (
    <World>
      <D1Defs />
      <JewellerCounter f={f} push={push} reach={reach} glint={glint} />
    </World>
  );
};

/* ------------------------------------------------------------------ */
/* Title + 02: the Manthan sea, the five diyas                          */
/* ------------------------------------------------------------------ */

const ROW_Y = 1250;

/** Lakshmi's lotus: a glowing pink lotus that blooms over slot 3 on 'लक्ष्मी'. */
const Lotus: React.FC<{ f: number; k: number }> = ({ f, k }) => {
  if (k <= 0.01) return null;
  const open = ramp(k, 0, 1, "back");
  const petals = [-64, -40, -18, 0, 18, 40, 64];
  return (
    <g opacity={Math.min(1, k * 1.4)}>
      <circle r={150} fill="url(#d1Glow)" opacity={0.9} />
      {petals.map((a, i) => (
        <g key={a} transform={`rotate(${a * open}) translate(0,-6)`}>
          <path
            d="M0 0C-22 -20 -24 -66 0 -96C24 -66 22 -20 0 0Z"
            fill={i === 3 ? "#FFC2D6" : "#F58AB0"}
            stroke="#B8346A"
            strokeWidth={2}
            transform={`scale(${0.75 + 0.25 * Math.cos((a * Math.PI) / 180)})`}
          />
        </g>
      ))}
      <ellipse cx={0} cy={4} rx={40} ry={12} fill="#F2C25A" />
      <circle cx={0} cy={-14} r={7 + Math.sin(f / 6) * 1.5} fill="#FFF4C8" />
    </g>
  );
};

export const SeaDiyasD1: React.FC<{ f: number }> = ({ f }) => {
  const [a] = SCENES.title;
  const [, b] = SCENES.diyas;
  const PA = cue("paanch", 267);
  const KR = cue("kram", 305);
  const LA = cue("lakshmi", 348);
  const DH = cue("dhanteras02", 407);
  const KY = cue("kyon", 430);
  const white = 1 - ramp(f, a, a + 8, "out");
  const z = track(f, [[a, 1.08], [b, 1.0, "io"]]);
  // the row waits small along the bottom under the title, then rises into place on 'पाँच'
  const up = ramp(f, PA - 4, PA + 16, "out");
  const rowY = 1690 - (1690 - ROW_Y) * up;
  const rowS = 0.62 + 0.33 * up;
  const show = [0, 1, 2, 3, 4].map((i) => 0.55 + 0.45 * ramp(f, PA + i * 5, PA + i * 5 + 10, "out"));
  const labels = up;
  const thread = ramp(f, KR - 2, KR + 22, "io");
  const lotus = ramp(f, LA - 4, LA + 14, "out") * (1 - 0.5 * ramp(f, DH - 6, DH + 10, "io"));
  const slide = ramp(f, DH - 6, DH + 16, "io");
  const q = ramp(f, KY - 2, KY + 6, "out");
  const qPop = track(f - KY + 2, [[0, 0.5], [7, 1.18, "out"], [11, 1, "io"]]);
  // slide: diya 1 moves toward the centre and grows; the rest dim
  const x0 = slotX(0);
  const tx = (540 - x0) * 0.55 * slide;
  const zs = 1 + 0.32 * slide;
  const threadX = slotX(0) + (slotX(4) - slotX(0)) * thread;
  return (
    <World>
      <D1Defs />
      <g transform={`translate(540 900) scale(${z}) translate(-540 -900)`}>
        <KshiraSagar f={f} cam={{ x: 0, y: 0, z: 1 }} glow={0.55} swell={0.3} />
        <rect x={0} y={0} width={W} height={1920} fill="#0C0A1C" opacity={0.36} />
        <Motes f={f} n={30} seed="d1sea" color="#FFE6A3" dir={-1} speed={0.6} size={3} o={0.7} />
      </g>
      <g transform={`translate(${x0 + tx} ${ROW_Y}) scale(${zs}) translate(${-x0} ${-ROW_Y})`}>
        {thread > 0 ? (
          <path d={`M${slotX(0)} ${rowY + 40}L${threadX} ${rowY + 40}`} stroke="#FFD36B" strokeWidth={4} strokeLinecap="round" opacity={0.85 * up} strokeDasharray="2 10" />
        ) : null}
        <g transform={`translate(${slotX(2)} ${rowY - 150})`}>
          <Lotus f={f} k={lotus} />
        </g>
        <DiyaRow f={f} y={rowY} show={show} lit={[0, 0, 0, 0, 0]} labels={labels} highlight={slide > 0.01 ? 0 : -1} hl={slide} scale={rowS} />
        {q > 0 ? (
          <text x={x0 + 10} y={rowY - 110} textAnchor="middle" fontFamily={CINZEL} fontWeight={900} fontSize={150} fill="#FFD36B" opacity={q} transform={`translate(${x0 + 10} ${rowY - 150}) scale(${qPop}) translate(${-(x0 + 10)} ${-(rowY - 150)})`} style={{ filter: "drop-shadow(0 0 18px rgba(255,201,77,0.8))" }}>
            ?
          </text>
        ) : null}
      </g>
      <Vignette o={0.55} />
      {white > 0 ? <rect x={0} y={0} width={W} height={1920} fill="#FFF4D6" opacity={white * 0.9} /> : null}
    </World>
  );
};
