/** The shadow standing up into Chhaya over [a, b]: first the floor shadow flattens, then she rises. */
const RisingChhaya: React.FC<{ f: number; a: number; b: number; x: number; y: number; s: number; id: string; hands?: [[number, number], [number, number]]; lookX?: number; noLie?: boolean }> = ({
  f,
  a,
  b,
  x,
  y,
  s,
  id,
  hands,
  lookX = 0.4,
  noLie = false,
}) => {
  const r = prog(f, a, b, Easing.linear);
  const lie = prog(r, 0, 0.45);
  const up = interpolate(r, [0.45, 1], [0, 1], { ...clamp, easing: outBack });
  const eyes = prog(f, b - 2, b + 6);
  return (
    <g>
      {r < 0.45 ? (
        noLie ? null : <g transform={`translate(${x} ${y}) scale(1.02 ${-0.8 * (1 - lie) - 0.02}) translate(${-x} ${-y})`} filter="url(#nvSil)" opacity={0.8}>
          <SanjnaStanding id={`${id}-sh`} f={f} x={x} y={y} s={s} eyes={0} hands={hands} />
        </g>
      ) : (
        <g transform={`translate(${x} ${y}) scale(${1 - 0.08 * (1 - up)} ${Math.max(0.02, up)}) translate(${-x} ${-y})`}>
          <Chhaya id={id} f={f} x={x} y={y} s={s} eyes={eyes} lookX={lookX} smile={0} hands={hands} />
        </g>
      )}
      <ellipse cx={x} cy={y} rx={220 * s * 1.4} ry={40} fill="#4A3A78" opacity={(noLie ? r * 2 : 1) * 0.35 * (1 - up * 0.6)} filter="url(#nvBlur6)" />
      <Motes f={f} x={x - 160} y={y - 700 * s} w={320} h={700 * s} n={22} o={interpolate(r, [0.3, 0.6, 1.4], [0, 1, 0], clamp)} />
    </g>
  );
};

